const bx = (en, zh) => ({ en, zh });

const WEEKDAYS = {
  Thu: bx('Thursday', '周四'),
  Fri: bx('Friday', '周五'),
  Sat: bx('Saturday', '周六'),
  Sun: bx('Sunday', '周日'),
  Mon: bx('Monday', '周一'),
  Tue: bx('Tuesday', '周二'),
  Wed: bx('Wednesday', '周三'),
};

function calDate(iso, enLabel, zhLabel) {
  return bx(enLabel || iso.slice(5), zhLabel || iso.slice(5).replace('-', '月') + '日');
}

function dayTpl({
  id,
  num,
  iso,
  weekday,
  routeEn,
  routeZh,
  titleEn,
  titleZh,
  metaEn,
  metaZh,
  img,
  imgAltEn,
  imgAltZh,
  descEn,
  descZh,
  timeline = [],
  activities = [],
}) {
  const [, m, d] = iso.split('-');
  const enCal = `Jun ${parseInt(d, 10)}`;
  const zhCal = `${parseInt(m, 10)}月${parseInt(d, 10)}日`;
  return {
    id,
    num: String(num).padStart(2, '0'),
    day: WEEKDAYS[weekday] || bx(weekday, weekday),
    date: bx(`${enCal} · ${routeEn}`, `${zhCal} · ${routeZh}`),
    title: bx(titleEn, titleZh),
    meta: bx(metaEn, metaZh),
    img,
    imgAlt: bx(imgAltEn, imgAltZh),
    desc: bx(descEn, descZh),
    timeline,
    activities,
    tripDate: iso,
  };
}

function act(icon, nameEn, nameZh, descEn, descZh, costEn = '', costZh = '') {
  const o = { icon, name: bx(nameEn, nameZh), desc: bx(descEn, descZh) };
  if (costEn) o.cost = bx(costEn, costZh);
  return o;
}

